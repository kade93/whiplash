// 코드의 UI 문자열은 전부 영어로 쓰고 t("…") 로 감싼다. 표에 없으면 영어가 그대로 나온다. (영어 먼저, 한국어·일본어는 번역)
// 형식 문자열은 tf("…%d…", 값) — %@ %d %.1f 는 String(format:) 규칙.

enum Lang: String, CaseIterable {
    case ko, en, ja

    var title: String {
        switch self {
        case .ko: return "한국어"
        case .en: return "English"
        case .ja: return "日本語"
        }
    }

    static var current: Lang = {
        if let saved = UserDefaults.standard.string(forKey: "lang"), let l = Lang(rawValue: saved) { return l }
        return .en                                   // 기본은 영어 (설정 ▸ 언어에서 바꿈)
    }() {
        didSet { UserDefaults.standard.set(current.rawValue, forKey: "lang") }
    }
}

/// 원문은 영어. 표에 없으면 영어가 그대로 나온다. 표: 영어 → (한국어, 일본어)
func t(_ en: String) -> String {
    guard Lang.current != .en, let row = L10n.table[en] else { return en }
    return Lang.current == .ko ? row.0 : row.1
}

func tf(_ en: String, _ args: CVarArg...) -> String {
    String(format: t(en), locale: nil, arguments: args)
}

